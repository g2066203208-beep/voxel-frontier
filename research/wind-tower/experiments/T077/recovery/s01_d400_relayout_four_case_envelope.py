def sha_bytes(raw):
    return hashlib.sha256(raw).hexdigest()


def sha_path(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def load_exact_artifacts(zip_dir, manifest_path):
    manifest = read_csv(manifest_path)
    if len(manifest) != 16 or len({(r["case"], r["batch"]) for r in manifest}) != 16:
        raise ValueError("Expected exactly 16 unique archived batch records")
    frames = []
    verified = []
    for r in manifest:
        name = r["case"] + "-" + r["batch"] + ".zip"
        p = zip_dir / name
        rawzip = p.read_bytes()
        if sha_bytes(rawzip) != r["zip_sha256"]:
            raise ValueError("ZIP byte hash mismatch: " + name)
        with zipfile.ZipFile(io.BytesIO(rawzip)) as z:
            bad = z.testzip()
            if bad is not None:
                raise ValueError("ZIP CRC error: " + bad)
            names = [n for n in z.namelist() if n.endswith("_31seg.csv.gz")]
            if len(names) != 1:
                raise ValueError("Expected one original 31seg gzip per ZIP: " + name)
            gz = z.read(names[0])
        if sha_bytes(gz) != r["gzip_sha256"]:
            raise ValueError("GZIP SHA mismatch: " + name)
        csvraw = gzip.decompress(gz)
        if sha_bytes(csvraw) != r["uncompressed_csv_sha256"]:
            raise ValueError("Uncompressed CSV SHA mismatch: " + name)
        df = pd.read_csv(io.BytesIO(csvraw))
        if len(df) != int(r["rows"]) or not REQUIRED.issubset(df.columns):
            raise ValueError("CSV schema/row mismatch: " + name)
        if df.case.nunique() != 1 or df.case.iloc[0] != r["case"]:
            raise ValueError("Case identity mismatch: " + name)
        numeric = df[list(REQUIRED - {"case", "segment"})].to_numpy(dtype=float)
        if not np.isfinite(numeric).all():
            raise ValueError("Nonfinite six-component history: " + name)
        frames.append(df[list(sorted(REQUIRED))].copy())
        verified.append({"case": r["case"], "batch": r["batch"],
                         "run_id": r["run_id"], "artifact_id": r["artifact_id"],
                         "zip_sha256": r["zip_sha256"],
                         "gzip_sha256": r["gzip_sha256"],
                         "csv_sha256": r["uncompressed_csv_sha256"],
                         "rows": len(df)})
    x = pd.concat(frames, ignore_index=True)
    if len(x) != 1488124 or x.case.nunique() != 4 or x.segment.nunique() != 31:
        raise ValueError("Four-case/31-segment/full-history cardinality mismatch")
    if x[["case", "segment", "time_s"]].duplicated().any():
        raise ValueError("Duplicated case/segment/time key")
    for (case, seg), q in x.groupby(["case", "segment"], sort=False):
        t = np.sort(q.time_s.to_numpy(float))
        if (len(t) != 12001 or abs(t[0] - 100.0) > 1e-7
                or abs(t[-1] - 700.0) > 1e-7
                or not np.allclose(np.diff(t), 0.05, atol=1e-7, rtol=0)):
            raise ValueError("Invalid time grid for " + case + "/" + seg)
    return x, verified


def envelope(seg, g, ring, d, qcases, gv):
    # Same T073/T077 sectional algorithm and T077 load combination as earlier
    # unrelocated D400 scan; this is not independent model verification.
    t077.e01.FY = 360.0
    t077.e01.FYC = 360.0
    Nc, Mc, NsA, MsA, Np1, Mp1 = t077.capacity_components(seg, g, ring, ETA)
    area = math.pi * d * d / 4.0
    Nb, Mb = t077.upper_capacity(Nc + area * NsA + 8 * Np1,
                                Mc + area * MsA + 8 * Mp1)
    ea = max(t077.EA_MIN_MM, float(g["D_m"]) * 1000.0 / 30.0)
    states = []
    for case, q in qcases.items():
        r = t077.evaluate_one(seg, q, gv, ea, Nb, Mb, 8, ETA)
        states.append({**r, "case": case})
    return max(states, key=lambda r: r["util"])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--zip-dir", type=Path, required=True)
    p.add_argument("--geometry", type=Path, required=True)
    p.add_argument("--outdir", type=Path, required=True)
    p.add_argument("--manifest", type=Path, default=HERE /
                   "S06_RECOVERED_16_ARTIFACT_SHA256_MANIFEST_20261024.csv")
    p.add_argument("--branch", type=Path, default=HERE /
                   "S01_D400_D500_UNMOVED_CAGE_CLEARANCE_31SEG_20261025.csv")
    p.add_argument("--t057", type=Path, default=HERE.parents[1] / "T057" / "inputs" /
                   "BASE001_T057_EVIDENCE_RECONCILED_HRB335_Q345_PTBF8_CONTACT_RNA_R2.inp")
    args = p.parse_args()
    for path, expected in ((args.t057, T057_SHA), (args.branch, BRANCH_SHA),
                           (args.geometry, GEOMETRY_SHA)):
        actual = sha_path(path)
        if actual != expected:
            raise ValueError(f"Frozen input mismatch {path}: {actual} != {expected}")
    x, verified = load_exact_artifacts(args.zip_dir, args.manifest)
    geom = t077.read_geom()
    rings = t077.read_rings(geom)
    gravity = t077.load_gravity()
    branch = {r["segment"]: r for r in read_csv(args.branch)}
    relayout = {r["segment"]: r for r in read_csv(args.geometry)
                if r["branch"] == "D400"}
    if not (len(geom) == len(rings) == len(gravity) == len(branch) == len(relayout) == 31):
        raise ValueError("31 segment metadata mismatch")

    result = []
    max_old_regression = 0.0
    for seg in sorted(geom):
        b, h, g = branch[seg], relayout[seg], geom[seg]
        d = int(b["d400_screen_d_mm"])
        if int(h["diameter_mm"]) != d or h["segment"] != seg:
            raise ValueError("Diameter/segment identity mismatch: " + seg)
        shift = float(h["straight_endpoint_shift_for_5mm_mm"])
        old = rings[seg]
        new = (old[0] + shift, old[1] - shift, old[2])
        if new[0] >= new[1]:
            raise ValueError("Rebar layers crossed: " + seg)
        qcases = {case: q.sort_values("time_s").reset_index(drop=True)
                  for case, q in x.loc[x.segment == seg].groupby("case")}
        if len(qcases) != 4:
            raise ValueError("Incomplete cases for " + seg)
        gv = {c: float(gravity.loc[seg, c]) for c in
              ("Fx_kN", "Fy_kN", "Fz_kN", "Mx_kNm", "My_kNm", "Mz_kNm")}
        before = envelope(seg, g, old, d, qcases, gv)
        after = envelope(seg, g, new, d, qcases, gv)
        old_err = abs(before["util"] - float(b["d400_conditional_u"]))
        max_old_regression = max(max_old_regression, old_err)
        if old_err > 1e-6:
            raise ValueError(f"Unrelocated full-history regression failed {seg}: {old_err}")
        switch = any((before[k] != after[k]) for k in ("case", "time_s",
                                                       "gamma_G", "gamma_P"))
        result.append({
            "segment": seg, "d400_mm": d, "straight_radial_shift_mm": shift,
            "eta_T078_design_not_native": ETA,
            "before_case": before["case"], "before_time_s": before["time_s"],
            "before_gamma_G": before["gamma_G"], "before_gamma_P": before["gamma_P"],
            "before_N_design_kN": before["N_design_kN"],
            "before_M_design_kNm": before["M_design_kNm"],
            "before_Mcap_kNm": before["Mcap_kNm"], "before_full_u": before["util"],
            "after_case": after["case"], "after_time_s": after["time_s"],
            "after_gamma_G": after["gamma_G"], "after_gamma_P": after["gamma_P"],
            "after_N_design_kN": after["N_design_kN"],
            "after_M_design_kNm": after["M_design_kNm"],
            "after_Mcap_kNm": after["Mcap_kNm"], "after_full_u": after["util"],
            "full_u_change": after["util"] - before["util"],
            "control_state_changed": switch,
            "status": "FULL_HISTORY_SECTION_SCREEN_ONLY_NO_CODE_OR_ABAQUS_PASS",
        })
    if len(result) != 31:
        raise ValueError("Expected 31 complete segment envelopes")
    args.outdir.mkdir(parents=True, exist_ok=True)
    outcsv = args.outdir / "S01_D400_RELAYOUT_4CASE_31SEG_FULL_ENVELOPE.csv"
    outjson = args.outdir / "S01_D400_RELAYOUT_4CASE_31SEG_FULL_ENVELOPE_MANIFEST.json"
    if outcsv.exists() or outjson.exists():
        raise FileExistsError("Refusing to overwrite prior result")
    with outcsv.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(result[0]))
        writer.writeheader()
        writer.writerows(result)
    top = max(result, key=lambda r: r["after_full_u"])
    meta = {
        "scientific_status": "S01_SCREEN_ONLY_NOT_STANDARD_OR_NATIVE_PASS",
        "rows": len(result), "history_records": len(x),
        "cases": sorted(x.case.unique().tolist()), "segments": 31,
        "time_s": [100.0, 700.0], "dt_s": 0.05,
        "source_artifacts": verified,
        "input_sha256": {
            "frozen_T057": sha_path(args.t057),
            "S06_manifest": sha_path(args.manifest),
            "D400_branch": sha_path(args.branch),
            "straight_T3D2_geometry": sha_path(args.geometry),
            "T071_geometry": sha_path(t077.GEOM),
            "T073_radii": sha_path(t077.RADII),
            "T074_gravity": sha_path(t077.GFILE),
            "T077_algorithm": sha_path(Path(t077.__file__)),
            "T073_E01_algorithm": sha_path(Path(t077.e01.__file__)),
            "this_script": sha_path(Path(__file__)),
        },
        "output_csv_sha256": sha_path(outcsv),
        "old_envelope_regression_max_abs_u": max_old_regression,
        "after_u_gt_1_segments": sum(r["after_full_u"] > 1.0 for r in result),
        "control_state_changed_segments": [r["segment"] for r in result
                                           if r["control_state_changed"]],
        "max_after_u_segment": top["segment"], "max_after_u": top["after_full_u"],
        "CSEG_02": next(r for r in result if r["segment"] == "CSEG_02"),
        "numerical_regression_tolerance": "1e-6 utilization (serialization/code replay only)",
        "physical_error_budget": "NEED_ESTIMATE: section discretization, load identity, "
                                 "material/detailing/PT, native mesh and V&V",
        "geometry_target_mm": 5.0, "geometry_target_is_code_requirement": False,
        "PT_state": "T078_DESIGN_ETA_PROXY_NOT_NATIVE_EQUILIBRIUM",
        "Abaqus_native": "NOT_RUN", "new_INP": False,
        "STANDARD_REF_OFFICIAL": "NO_NEW_AUTHORIZED_CLAUSE_OR_FULLTEXT_READING",
        "FIG": "NO_NEW_NATIVE_RESPONSE_FIGURE",
        "HOLD": "S01 unique compliant buildable design branch and P0/Pe native "
                "equilibrium not frozen; S02+ blocked",
    }
    outjson.write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n",
                       encoding="utf-8")
    print(json.dumps({
        "status": meta["scientific_status"], "rows": len(result),
        "history_records": len(x),
        "old_regression_max_abs_u": max_old_regression,
        "max_after_u": meta["max_after_u"],
        "max_after_u_segment": meta["max_after_u_segment"],
        "after_u_gt_1_segments": meta["after_u_gt_1_segments"],
        "control_state_changed_segments": meta["control_state_changed_segments"],
        "CSEG_02_before": meta["CSEG_02"]["before_full_u"],
        "CSEG_02_after": meta["CSEG_02"]["after_full_u"],
        "csv_sha256": meta["output_csv_sha256"],
    }, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
