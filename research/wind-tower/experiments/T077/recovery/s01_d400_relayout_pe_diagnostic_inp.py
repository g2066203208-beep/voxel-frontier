#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate ONE separate D400 + Pe-input-proxy Abaqus INP from frozen T057.

STATIC MODEL TRANSFORMATION ONLY. Not a construction, standards, Data Check,
PT equilibrium, fatigue or seismic PASS. Never overwrite T057/T070.

Input geometry is the SHA-locked 62-row straight-T3D2 sensitivity CSV
generated by s01_d400_d500_straight_t3d2_exact.py. The 5 mm target is
an arbitrary research sensitivity, NOT a normative minimum.

Usage:
 python s01_d400_relayout_pe_diagnostic_inp.py --inp /path/T057.inp \
   --geometry /tmp/geometry/S01_D400_D500_31SEG_STRAIGHT_T3D2_EXACT_GEOMETRY.csv \
   --outdir /tmp/d400_diagnostic
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import re
from pathlib import Path

SOURCE_SHA256 = "c5652eae36ad8b60ef2caed1ab12e147b149f5199d40b83a3cb2af4dfaf672db"
GEOMETRY_SHA256 = "85a462b18833993853e85b80b755c3097a2698cbc39c18fae5d4b4d226e5dcaf"
P0_PA = 1280000000.0
PE_PA = 985951362.9616609
PT_AREA_M2 = 0.04032
MATERIAL = (
    "*Material, name=HRB400_D400_DIAGNOSTIC\n"
    "*Density\n7850.,\n*Elastic\n2e+11, 0.3\n"
    "*Plastic\n400000000., 0.\n"
)
PT_CARD = "PT_36x15p2-1.SET_PT_ALL_ELEMS, 1.28e+09, "
PT_NEW = "PT_36x15p2-1.SET_PT_ALL_ELEMS, 985951362.9616609, "
OLD_SECTION = "*Solid Section, elset=SET_ALL, material=HRB335_T057\n0.000490874,"
SECTION_RE = re.compile(r"\*Solid Section, elset=SET_ALL, material=HRB335_T057\n0\.000490874,")
PART_RE = re.compile(r"(?s)(\*Part, name=(RBLONG_\d{2})\n\*Node\n)(.*?)(\*Element, type=T3D2\n.*?\*End Part)")
NODES_END = "*Element, type=T3D2\n"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def require(condition: bool, msg: str) -> None:
    if not condition:
        raise ValueError(msg)


def load_geometry(path: Path) -> dict:
    raw = path.read_bytes()
    require(sha(raw) == GEOMETRY_SHA256, "62-row geometry source SHA256 mismatch: " + sha(raw))
    rows = list(csv.DictReader(raw.decode("utf-8-sig").splitlines()))
    require(len(rows) == 62, "geometry CSV must contain exactly 62 rows")
    d400 = {r["segment"]: r for r in rows if r["branch"] == "D400"}
    require(len(d400) == 31, "D400 requires exactly 31 unique segments")
    require(all(r["status"] == "GEOMETRY_SENSITIVITY_ONLY_NO_NATIVE_OR_CODE_PASS"
                for r in d400.values()), "unexpected geometry provenance")
    return d400


def rewrite_part(full: str, seg: int, row: dict) -> tuple[str, dict]:
    name = f"RBLONG_{seg:02d}"
    prefix = f"*Part, name={name}\n*Node\n"
    require(full.startswith(prefix), "unexpected part prefix: " + name)
    node_start = len(prefix)
    node_end = full.index(NODES_END, node_start)
    node_block = full[node_start:node_end]
    lines = node_block.splitlines(keepends=True)
    parsed = []
    for line in lines:
        if not line.strip():
            continue
        vals = [x.strip() for x in line.strip().split(",")]
        require(len(vals) == 4, f"{name} unexpected node row: {line[:70]}")
        nid = int(vals[0])
        x, y, z = map(float, vals[1:])
        parsed.append((nid, x, y, z, line))
    require(len(parsed) >= 4 and len(parsed) % 2 == 0, name + " node count invalid")
    require([v[0] for v in parsed] == list(range(1, len(parsed) + 1)),
            name + " node ids must be contiguous")
    y_levels = sorted(set(v[2] for v in parsed))
    require(len(y_levels) == 2, name + " unexpected vertical node layers")
    mid = {}
    for y in y_levels:
        radii = [math.hypot(v[1], v[3]) for v in parsed if v[2] == y]
        require(max(radii) - min(radii) > 0.05, name + " inner/outer rings not separable")
        mid[y] = (min(radii) + max(radii)) / 2
    diameter = int(row["diameter_mm"])
    delta = float(row["straight_endpoint_shift_for_5mm_mm"]) / 1000.0
    require(0 <= delta < 0.08 and diameter in (25, 28, 32, 36, 40, 50),
            name + " unexpected diameter/shift")
    require(float(row["achieved_min_clearance_mm"]) >= 4.99998,
            name + " research sensitivity target not attained")
    signs = []
    for _, x, y, z, _ in parsed:
        r = math.hypot(x, z)
        require(r > 0.5, name + " degenerate radial coordinate")
        signs.append(1 if r < mid[y] else -1)
    for j in range(0, len(signs), 2):
        require(signs[j] == signs[j+1], name + " bar switches radial layer")
    newlines = []
    changed = 0
    for (nid, x, y, z, original), sign in zip(parsed, signs):
        if delta == 0:
            newlines.append(original)
        else:
            r = math.hypot(x, z)
            xx = x + sign * delta * x / r
            zz = z + sign * delta * z / r
            newlines.append(f"{nid}, {xx:.14g}, {y:.14g}, {zz:.14g}\n")
            changed += 1
    area = math.pi * (diameter / 1000.0)**2 / 4
    suffix = full[node_end:]
    require(suffix.count(OLD_SECTION) == 1, name + " source section differs")
    new_section = (f"*Solid Section, elset=SET_ALL, material=HRB400_D400_DIAGNOSTIC\n"
                   f"{area:.14g},")
    suffix = suffix.replace(OLD_SECTION, new_section, 1)
    new_full = prefix + "".join(newlines) + suffix
    return new_full, {
        "segment": f"CSEG_{seg:02d}", "diameter_mm": diameter,
        "bar_elements": len(parsed) // 2, "shift_mm": delta * 1000,
        "changed_node_lines": changed, "area_each_m2": area,
        "original_area_each_m2": 0.000490874,
        "material": "HRB400_D400_DIAGNOSTIC",
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--inp", required=True, type=Path)
    ap.add_argument("--geometry", required=True, type=Path)
    ap.add_argument("--outdir", required=True, type=Path)
    args = ap.parse_args()
    source_raw = args.inp.read_bytes()
    require(sha(source_raw) == SOURCE_SHA256, "frozen T057 SHA256 mismatch")
    source = source_raw.decode("utf-8")
    geometry = load_geometry(args.geometry)
    require(source.count(PT_CARD) == 1, "PT P0 card missing/duplicated")
    require(source.count("*Material, name=HRB335_T057\n") == 1,
            "HRB335 material definition missing/duplicated")
    require(source.count("*Solid Section, elset=SET_ALL, material=HRB335_T057") == 31,
            "expected 31 original longitudinal sections")
    part_spans = list(PART_RE.finditer(source))
    require(len(part_spans) == 31, f"expected 31 RBLONG parts, got {len(part_spans)}")
    require({m.group(2) for m in part_spans} == {f"RBLONG_{i:02d}" for i in range(1,32)},
            "missing/duplicate RBLONG part")
    replacements = {}
    records = []
    for m in part_spans:
        idx = int(m.group(2).split("_")[1])
        rewritten, rec = rewrite_part(m.group(0), idx, geometry[f"CSEG_{idx:02d}"])
        replacements[m.group(0)] = rewritten
        records.append(rec)
    # Apply in reverse source order; no global substitutions to frozen geometry.
    changed = source
    for m in reversed(part_spans):
        changed = changed[:m.start()] + replacements[m.group(0)] + changed[m.end():]
    changed = changed.replace("*Material, name=HRB335_T057\n",
                              MATERIAL + "*Material, name=HRB335_T057\n", 1)
    changed = changed.replace(PT_CARD, PT_NEW, 1)
    require(changed.count("*Solid Section, elset=SET_ALL, material=HRB400_D400_DIAGNOSTIC") == 31,
            "31 D400 sections not achieved")
    require(changed.count("*Solid Section, elset=SET_HOOP_ALL, material=HRB335_T057") == 1,
            "historical HRB335 hoop changed")
    require(changed.count("*Solid Section, elset=SET_TIE_ALL, material=HRB335_T057") == 1,
            "historical HRB335 ties changed")
    require(changed.count(PT_NEW) == 1 and changed.count(PT_CARD) == 0,
            "PT input proxy mismatch")
    # Exact reversibility: all untouched parts, assembly, contact, RNA and steps
    # must return byte-for-byte to the frozen parent.
    restored = changed.replace(PT_NEW, PT_CARD, 1)
    restored = restored.replace(MATERIAL + "*Material, name=HRB335_T057\n",
                                "*Material, name=HRB335_T057\n", 1)
    for m in reversed(list(PART_RE.finditer(restored))):
        name = m.group(2)
        old = next(p.group(0) for p in part_spans if p.group(2) == name)
        restored = restored[:m.start()] + old + restored[m.end():]
    require(restored.encode("utf-8") == source_raw, "inverse patch cannot restore T057 exactly")
    output = args.outdir / "S01_D400_RELAYOUT_Pe_PROXY_DIAGNOSTIC_ONLY.inp"
    manifest = args.outdir / "S01_D400_RELAYOUT_Pe_PROXY_DIAGNOSTIC_MANIFEST.json"
    require(not output.exists() and not manifest.exists(), "refuse to overwrite diagnostic files")
    args.outdir.mkdir(parents=True, exist_ok=True)
    candidate_raw = changed.encode("utf-8")
    output.write_bytes(candidate_raw)
    data = {
        "stage": "S01", "status": "STATIC_DIAGNOSTIC_ONLY_HOLD",
        "parent": str(args.inp), "parent_sha256": sha(source_raw),
        "geometry_csv_sha256": sha(args.geometry.read_bytes()),
        "script_sha256": sha(Path(__file__).read_bytes()),
        "candidate_sha256": sha(candidate_raw), "candidate_bytes": len(candidate_raw),
        "reverse_patch_exact_parent": True, "sections": sorted(records, key=lambda r:r["segment"]),
        "changed_longitudinal_segments": 31,
        "unchanged_hoop_and_tie_material": "HRB335_T057 (MIXED-MATERIAL DIAGNOSTIC, NOT CODE DESIGN)",
        "D400_constitutive_assumption": "E=200GPa, nu=0.3, density=7850kg/m3, perfectly plastic fy=400MPa; NOT CALIBRATED",
        "section_design_strength_screen": "fy=fyc=360MPa in T077 screen; distinct from material yield",
        "PT_initial_input_Pa": PE_PA, "PT_Pe_nominal_N": PE_PA*PT_AREA_M2,
        "PT_P0_parent_nominal_N": P0_PA*PT_AREA_M2,
        "PT_Pe_is_native_equilibrated": False,
        "geometry_5mm_target_is_normative": False,
        "native_Abaqus_Data_Check": "NOT_RUN",
        "PT_gravity_contact_equilibrium": "NOT_RUN",
        "construction_and_standard_acceptance": "HOLD_NBT10907_AUTHORIZED_TEXT_AND_DETAILING",
        "material_fatigue": "NOT_RUN", "earthquake_results": 0,
        "physical_error_budget": "NOT_ESTIMATED",
        "FIG": "NONE", "TAB": "31-segment transformation manifest",
    }
    manifest.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"candidate_sha256": data["candidate_sha256"],
                      "candidate_bytes": len(candidate_raw),
                      "segments": len(records), "changed_nodes": sum(x["changed_node_lines"] for x in records),
                      "reverse_patch_exact_parent": True,
                      "status": data["status"]}, indent=2))


if __name__ == "__main__":
    main()
